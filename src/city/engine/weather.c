typedef struct {
  u8 temperature, wind, rainfall;
} WeatherProperties;

static const WeatherProperties kWeatherProperties[CITY_WEATHER_COUNT] = {
  [CITY_WEATHER_COLD] = {80, 15, 0},
  [CITY_WEATHER_CLEAR] = {165, 30, 0},
  [CITY_WEATHER_HOT] = {210, 0, 0},
  [CITY_WEATHER_FOGGY] = {100, 0, 15},
  [CITY_WEATHER_CHILLY] = {145, 15, 15},
  [CITY_WEATHER_OVERCAST] = {175, 5, 15},
  [CITY_WEATHER_SNOW] = {80, 10, 30},
  [CITY_WEATHER_RAIN] = {150, 30, 30},
  [CITY_WEATHER_WINDY] = {175, 60, 30},
  [CITY_WEATHER_BLIZZARD] = {60, 100, 60},
  [CITY_WEATHER_HURRICANE] = {140, 100, 60},
  [CITY_WEATHER_TORNADO] = {175, 100, 60},
};

void AdvanceCityWeather(City *city) {
  int next = kWeatherTransitions[city->clock.quarter][city->weather.state][Sc2kCrtRand(city) & 7];
  const WeatherProperties *properties = &kWeatherProperties[next];
  city->weather.rainfall = (city->weather.rainfall + properties->rainfall) / 2;
  city->weather.wind = (city->weather.wind + properties->wind) / 2;
  city->weather.temperature = (city->weather.temperature + properties->temperature) / 2;
  city->weather.state = next;
}
