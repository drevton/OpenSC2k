// Map one stock Windows-1252 byte to its Unicode code point. The mapping is total for all byte values and changes no
// native string storage.
u16 DecodeCityWindows1252Byte(u8 byte) {
  return byte >= 128 && byte < 160 ? kWindows1252[byte - 128] : byte;
}

// Project a Unicode code point to one stock Windows-1252 byte. Unrepresentable characters become '?'; callers use
// CanEncodeLegacyCityText when loss would be unacceptable.
u8 EncodeCityWindows1252Character(u32 unicode) {
  if (unicode < 128 || (unicode >= 160 && unicode <= 255)) return unicode;
  for (int index = 0; index < 32; ++index)
    if (unicode == kWindows1252[index]) return index + 128;
  return '?';
}

