// Find a valid tile's adjacent aligned rail incline and return its transition direction. Returns the routine's
// no-transition value when none matches; neighbors outside the map are skipped.
int FindCityRailTransition(const City *city, TileIndex tile) {
  static const i8 kX[] = {0, 0, -1, 1}, kY[] = {-1, 1, 0, 0};
  static const u8 kSlopes[] = {1, 3, 2, 4};
  for (int side = 0; side < 4; ++side) {
    TileIndex neighbor = GetRelativeTileOrInvalid(city, tile, kX[side], kY[side]);
    if (neighbor != INVALID_TILE && ReadTile(city, neighbor) == TK_RAIL &&
        ReadTerrainCode(&city->tile[neighbor]) == kSlopes[side]) return side;
  }
  return -1;
}

// Read the axis of the requested straight infrastructure family on a valid tile. Returns -1 when the family or stored
// shape cannot represent a straight segment; does not infer a new connection.
int ReadCityStraightLineAxis(const City *city, TileIndex tile, int family) {
  int kind = ReadTile(city, tile);
  if (family && (family == TK_POWER_LINE ? !IsTileKindPlainPowerLine(kind) : kind != family)) return -1;
  if (kind == TK_HIGHWAY) return ReadCityHighwayAxis(&city->tile[tile]);
  if (!IsTileKindPlainPowerLine(kind) && !IsTileKindPlainTransport(kind)) return -1;
  int shape = ReadTerrainCode(&city->tile[tile]);
  if (IsTileKindPlainPowerLine(kind)) {
    if (shape >= CITY_TERRAIN_SHAPE_1 && shape <= CITY_TERRAIN_SHAPE_4) return -1;
    if (shape >= CITY_TERRAIN_SHAPE_9 && shape <= CITY_TERRAIN_SHAPE_12) return 1;
  } else {
    if (kLineTerrainOverrideBySlope[shape]) return -1;
    if (kind == TK_RAIL && FindCityRailTransition(city, tile) >= 0) return -1;
  }
  int mask = ReadTransportConnections(&city->tile[tile]);
  if (!(mask & CONN_NS)) return 0;
  if (!(mask & CONN_EW)) return 1;
  return -1;
}

// Determine whether a valid plain transport tile is a bend or junction rather than a straight or sloped piece. Reads
// stored connections and rail transitions without changing topology.
bool IsCityLineBendOrJunction(const City *city, TileIndex tile) {
  int kind = ReadTile(city, tile);
  if (!IsTileKindPlainTransport(kind) ||
      kLineTerrainOverrideBySlope[ReadTerrainCode(&city->tile[tile])]) return false;
  if (kind == TK_RAIL && FindCityRailTransition(city, tile) >= 0) return false;
  int mask = ReadTransportConnections(&city->tile[tile]);
  return (mask & CONN_EW) && (mask & CONN_NS);
}

// Clear one section's power or water supply flags and associated coverage state. Section must identify a complete map
// section; the caller owns scan ordering and layer invalidation.
void ClearCityUtilitySection(City *city, int section, bool water) {
  int width = city->map_width, columns = width / CITY_MAP_SECTION_SIZE;
  TileIndex first = section / columns * CITY_MAP_SECTION_SIZE * width + section % columns * CITY_MAP_SECTION_SIZE;
  TileInfo *restrict tiles = city->tile + first;
  for (int y = 0; y < CITY_MAP_SECTION_SIZE; ++y) {
    TileInfo *row = tiles + y * width;
    for (int x = 0; x < CITY_MAP_SECTION_SIZE; ++x) {
      int clear_flags = TF_VISITED | (water ?
          (row[x].kind == TK_WATER_TOWER ? 0 : TF_WATERED) : TF_POWERED);
      row[x].flags &= ~clear_flags;
    }
  }
}

// Test the requested corner for a valid building or highway footprint tile. Uses the family's native metadata and
// supported corner enum; does not reconstruct geometry from artwork IDs.
bool IsCityFootprintCorner(const City *city, TileIndex tile, int corner) {
  int kind = ReadTile(city, tile);
  if (IsTileKindBuilding(kind)) return IsCityBuildingCorner(city, tile, corner);
  if (IsTileKindHighwayBridge(kind) || IsTileKindMultiHighway(kind)) {
    int zone = IsTileKindHighwayBridge(kind) ? CityBridgeHighwayZone(city, tile) : ReadZoneByte(city, tile);
    int links = zone >> 6;
    return (((links & 1) << 1) | ((links ^ (links >> 1)) & 1)) == corner;
  }
  if (IsTileKindStraightHighwayFamily(kind)) {
    CityRect bounds = CityHighwayFootprintBounds(city, tile, &city->tile[0].terrain, sizeof(TileInfo));
    bool bottom = corner == CITY_BUILDING_CORNER_BOTTOM_LEFT || corner == CITY_BUILDING_CORNER_BOTTOM_RIGHT;
    CityPoint point = MapTilePt(city, tile);
    return point.x == (corner & 2 ? bounds.right - 1 : bounds.left) &&
        point.y == (bottom ? bounds.bottom - 1 : bounds.top);
  }
  return (ReadFootprintCorners(city, tile) & (CITY_ZONE_CORNER_0 << ((city->geography.rotation + corner) & 3))) != 0;
}

// Decode footprint corner bits for a valid native tile across building and highway families. Returns a value derived
// from stored links/rotation; callers must not treat the zone upper nibble as a generic corner mask.
int ReadFootprintCorners(const City *city, TileIndex tile) {
  int kind = city->tile[tile].kind;
  u32 classes = ReadCityTileClasses(kind);
  if ((classes & TCLASS_HIGHWAY) || IsTileKindHighwayBridge(kind)) {
    int zone = ReadTileZoneByte(&city->tile[tile]);
    if (IsTileKindHighwayBridge(kind))
      zone = CityBridgeHighwayZone(city, tile);
    else if (IsTileKindStraightHighwayFamily(kind)) {
      CityRect bounds = CityHighwayFootprintBounds(city, tile, &city->tile[0].terrain, sizeof(TileInfo));
      CityPoint point = MapTilePt(city, tile);
      int mask = 0;
      int rotation = city->geography.rotation;
      if (point.x == bounds.left && point.y == bounds.top) mask |= CITY_ZONE_CORNER_0 << rotation;
      if (point.x == bounds.left && point.y == bounds.bottom - 1) mask |= CITY_ZONE_CORNER_0 << ((rotation + 1) & 3);
      if (point.x == bounds.right - 1 &&
          point.y == bounds.bottom - 1) mask |= CITY_ZONE_CORNER_0 << ((rotation + 2) & 3);
      if (point.x == bounds.right - 1 && point.y == bounds.top) mask |= CITY_ZONE_CORNER_0 << ((rotation + 3) & 3);
      return mask;
    }
    return CityHighwayCornerMask(city, zone);
  }
  if (classes & TCLASS_SINGLE_FOOTPRINT) return CITY_ZONE_CORNER_MASK;
  if (kind == TK_CLEAR || IsTileKindExposedWater(kind) || (classes & (TCLASS_TREE | TCLASS_VARIANT |
      TCLASS_POWER | TCLASS_PLAIN_TRANSPORT | TCLASS_GROUND_CROSSING |
          TCLASS_SURFACE_BRIDGE)))
    return 0;
  if (IsTileKindBuilding(kind))
    return CityBuildingCornerMask(city, tile, &city->tile[0].terrain, sizeof(TileInfo));
  return ReadTileZoneByte(&city->tile[tile]) & CITY_ZONE_CORNER_MASK;
}

