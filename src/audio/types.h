// Newspaper cue indices are distinct from these IDs.
typedef enum CityMusicResourceId {
  CITY_MUSIC_TRACK_00 = 10000, CITY_MUSIC_TRACK_01 = 10001, CITY_MUSIC_TRACK_02 = 10002,
  CITY_MUSIC_TRACK_03 = 10003, CITY_MUSIC_TRACK_04 = 10004, CITY_MUSIC_TRACK_05 = 10005,
  CITY_MUSIC_TRACK_06 = 10006, CITY_MUSIC_TRACK_07 = 10007, CITY_MUSIC_TRACK_08 = 10008,
  CITY_MUSIC_TRACK_09 = 10009, CITY_MUSIC_TRACK_10 = 10010, CITY_MUSIC_TRACK_11 = 10011,
  CITY_MUSIC_TRACK_12 = 10012, CITY_MUSIC_TRACK_13 = 10013, CITY_MUSIC_TRACK_14 = 10014,
  CITY_MUSIC_TRACK_15 = 10015, CITY_MUSIC_TRACK_16 = 10016, CITY_MUSIC_TRACK_17 = 10017,
  CITY_MUSIC_TRACK_18 = 10018,
  CITY_MUSIC_FIRST = CITY_MUSIC_TRACK_00, CITY_MUSIC_LAST = CITY_MUSIC_TRACK_18,
  CITY_MUSIC_TRACK_COUNT = CITY_MUSIC_LAST - CITY_MUSIC_FIRST + 1,
  CITY_MUSIC_SEQUENCE_COUNT = 5,
} CityMusicResourceId;

#endif
