Fixed FixedSqrt(Fixed value) {
  if (value <= 0) return 0;
  u64 square = (u64)value * FIXED_ONE;
  int bits = 64 - __builtin_clzll(square);
  u64 root = (u64)1 << ((bits + 1) / 2);
  for (;;) {
    u64 next = (root + square / root) / 2;
    if (next >= root) return root;
    root = next;
  }
}

static int SineSample(int index) {
  index &= 255;
  int offset = index & 63;
  int value = kFixedSineQuarter[index & 64 ? 64 - offset : offset];
  return index & 128 ? -value : value;
}

Fixed FixedSin(Fixed radians) {
  radians %= FIXED_TAU;
  if (radians < 0) radians += FIXED_TAU;
  i64 phase = radians * (256 * FIXED_ONE) / FIXED_TAU;
  int index = phase >> 16, fraction = phase & 65535;
  int first = SineSample(index), next = SineSample(index + 1);
  return first + (i64)(next - first) * fraction / FIXED_ONE;
}

Fixed FixedAtan2(Fixed y, Fixed x) {
  Fixed ax = FixedAbs(x), ay = FixedAbs(y);
  if (!ax && !ay) return 0;
  Fixed low = FixedMin(ax, ay), high = FixedMax(ax, ay);
  i64 position = low * (256 * FIXED_ONE) / high;
  int index = position >> 16, fraction = position & 65535;
  Fixed angle = kFixedAtanOctant[index];
  if (index < 256) angle += (i64)(kFixedAtanOctant[index + 1] - angle) * fraction / FIXED_ONE;
  if (ay > ax) angle = FIXED_PI / 2 - angle;
  if (x < 0) angle = FIXED_PI - angle;
  return y < 0 ? -angle : angle;
}

Fixed FixedExp(Fixed value) {
  // Relief needs only exp(-distance squared). Values beyond sixteen units
  // round below one Q16 step; reduce smaller arguments before the series.
  if (value <= -16 * FIXED_ONE) return 0;
  int squares = 0;
  while (FixedAbs(value) > FIXED_ONE / 8) {
    value /= 2;
    ++squares;
  }
  Fixed result = FIXED_ONE, term = FIXED_ONE;
  for (int i = 1; i <= 6; ++i) {
    term = FixedMul(term, value) / i;
    result += term;
  }
  while (squares--)
    result = FixedMul(result, result);
  return result;
}
