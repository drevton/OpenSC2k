"""Rasterize the bundled OpenTTD Sans into the C canvas's immutable glyph table."""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont
from build_interface_font import glyph as interface_glyph


ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "assets/fonts/openttd/OpenTTD-Sans.ttf"
OUTPUT = ROOT / "src/assets/canvas_font.inc"


def format_font_table(glyphs: list, size: int, table: str) -> str:
  rows, offsets, records = [], {}, []
  pool = "kCanvasFontRows" if table == "kCanvasFont" else "kCanvasHeadingFontRows"
  for metrics, masks in glyphs:
    masks = tuple(masks) or (0,)
    if masks not in offsets:
      offsets[masks] = len(rows)
      rows.extend(masks)
    records.append((*metrics, offsets[masks]))
  lines = [
    f"// Generated by tools/generate_canvas_font.py from OpenTTD Sans, {size} px.",
    "// Copyright OpenTTD-TTF contributors. GPL-2.0; see assets/fonts/openttd/LICENSE.",
    "// Glyph indexes use Windows-1252. Identical immutable row masks are shared.",
    "", f"static const u16 {pool}[] = {{",
  ]
  for start in range(0, len(rows), 8):
    lines.append("  " + ", ".join(f"0x{row:04X}" for row in rows[start:start + 8]) + ",")
  lines += ["};", ""]
  control = all(record == records[0] for record in records[:32])
  if control:
    width, height, advance, left, top, offset = records[0]
    lines += [
      "// Codes 0..31 all use the same unsupported-character glyph.",
      f"#define CANVAS_CONTROL_GLYPH {{{width}, {height}, {advance}, {left}, {top}, {pool} + {offset}}}",
      "#define CANVAS_CONTROL_GLYPHS_8 " + "\\",
      "  CANVAS_CONTROL_GLYPH, CANVAS_CONTROL_GLYPH, CANVAS_CONTROL_GLYPH, CANVAS_CONTROL_GLYPH, " + "\\",
      "  CANVAS_CONTROL_GLYPH, CANVAS_CONTROL_GLYPH, CANVAS_CONTROL_GLYPH, CANVAS_CONTROL_GLYPH",
      "",
    ]
  lines.append(f"const CityCanvasGlyph {table}[256] = {{")
  if control:
    lines += ["  CANVAS_CONTROL_GLYPHS_8, // " + str(code) + ".." + str(code + 7)
              for code in range(0, 32, 8)]
  for code, (width, height, advance, left, top, offset) in enumerate(records):
    if control and code < 32:
      continue
    lines.append(f"  {{{width}, {height}, {advance}, {left}, {top}, {pool} + {offset}}}, // {code}")
  lines += ["};", ""]
  if control:
    lines += ["#undef CANVAS_CONTROL_GLYPHS_8", "#undef CANVAS_CONTROL_GLYPH", ""]
  return "\n".join(lines)


def generate(size: int, output: Path, table: str, clear_pixel: int = 1) -> None:
  font = ImageFont.truetype(str(FONT), size)
  glyphs = []
  for code in range(256):
    character = bytes([code]).decode("cp1252", errors="replace")
    if code < 32 or character == "\ufffd":
      character = "?"
    left, top, right, bottom = font.getbbox(character, anchor="ls")
    width, height = right - left, bottom - top
    advance = round(font.getlength(character))
    assert 0 <= width <= 16 and 0 <= height <= 16
    image = Image.new("1", (max(1, width), max(1, height)))
    ImageDraw.Draw(image).text((-left, -top), character, font=font, fill=1, anchor="ls")
    rows = [sum((1 << x) for x in range(width) if image.getpixel((x, y)))
            for y in range(height)]
    # Reserve the requested spacing after ink, including overhanging capitals.
    ink_right = max((row.bit_length() for row in rows), default=0)
    if ink_right:
      advance = max(advance, left + ink_right + clear_pixel)
    if size == 10:
      advance = interface_glyph(code, 1)[1]
    glyphs.append(((width, height, advance, left, top + size - 2), rows))
  output.write_text(format_font_table(glyphs, size, table))


if __name__ == "__main__":
  generate(10, OUTPUT, "kCanvasFont")
  generate(12, ROOT / "src/assets/canvas_heading_font.inc", "kCanvasHeadingFont")
