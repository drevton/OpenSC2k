#!/usr/bin/env python3
"""Compile editable STR_<numeric ID> : text entries into immutable C character arrays."""
import argparse
from pathlib import Path
import re


def read_strings(path):
  strings = {}
  escapes = {"n": "\n", "t": "\t", "\\": "\\", '"': '"'}
  source = path.read_text(encoding="utf-8")
  position = 0
  while position < len(source):
    number = source.count("\n", 0, position) + 1
    end = source.find("\n", position)
    if end < 0:
      end = len(source)
    line = source[position:end]
    if not line.strip() or line.lstrip().startswith("#"):
      position = end + 1
      continue
    match = re.match(r"STR_([0-9]+)[ \t]*:(?: )?", line)
    if not match:
      raise ValueError(f"{path}:{number}: expected STR_<numeric ID> : text")
    ident = int(match[1])
    if not 0 <= ident <= 65535 or ident in strings:
      raise ValueError(f"{path}:{number}: invalid or duplicate string ID {ident}")
    position += match.end()
    quoted = position < len(source) and source[position] == '"'
    if quoted:
      position += 1
    decoded = []
    while position < (len(source) if quoted else end):
      character = source[position]
      position += 1
      if quoted and character == '"':
        break
      if character == "\\":
        if source.startswith("x20", position):
          character = " "
          position += 3
        elif position < len(source) and source[position] in escapes:
          character = escapes[source[position]]
          position += 1
        else:
          raise ValueError(f"{path}:{number}: unsupported escape sequence")
      decoded.append(character)
    else:
      if quoted:
        raise ValueError(f"{path}:{number}: unterminated quoted value")
    end = source.find("\n", position)
    if end < 0:
      end = len(source)
    if source[position:end].strip():
      raise ValueError(f"{path}:{number}: unexpected text after closing quote")
    position = end + 1
    text = "".join(decoded)
    if "\0" in text:
      raise ValueError(f"{path}:{number}: embedded NUL is not supported")
    try:
      strings[ident] = text.encode("cp1252")
    except UnicodeEncodeError as error:
      raise ValueError(f"{path}:{number}: character is outside the interface's Windows-1252 character set") from error
  return strings


def c_literal(text):
  escapes = {10: r"\n", 9: r"\t", 34: r'\"', 92: r"\\", 63: r"\?"}
  return '"' + "".join(escapes.get(byte, chr(byte) if 32 <= byte < 127 else f"\\{byte:03o}")
      for byte in text) + '"'


def compile_strings(sources, destination):
  strings = {}
  origins = {}
  for source in sources:
    for ident, text in read_strings(source).items():
      if ident in strings:
        raise ValueError(f"{source}: duplicate STR_{ident}; already defined in {origins[ident]}")
      strings[ident] = text
      origins[ident] = source
  if not strings:
    raise ValueError("no strings in input catalogs")
  lines = ["// Generated by tools/compile_strings.py; edit the input catalog instead.",
      '#include "assets/catalog.h"', ""]
  for ident, text in sorted(strings.items()):
    if text:
      lines.append(f"static const char kString{ident}[] =")
      lines += [f"    {c_literal(text[start:start + 24])}" for start in range(0, len(text), 24)]
      lines[-1] += ";"
  lines += ["", "static const struct { u16 id; const char *text; } kStrings[] = {"]
  lines += [f"  {{{ident}, kString{ident}}}," for ident, text in sorted(strings.items()) if text]
  lines += ["};", "", "const char *ReadCityResourceString(CityResourceState *assets, int id) {",
      "  (void)assets;", "  int first = 0, last = sizeof(kStrings) / sizeof(kStrings[0]);",
      "  while (first < last) {", "    int middle = first + (last - first) / 2;",
      "    if (kStrings[middle].id < id) first = middle + 1;", "    else last = middle;", "  }",
      "  return first < (int)(sizeof(kStrings) / sizeof(kStrings[0])) && kStrings[first].id == id ?",
      '      kStrings[first].text : "";', "}", ""]
  destination.parent.mkdir(parents=True, exist_ok=True)
  destination.write_text("\n".join(lines), encoding="utf-8")
  print(f"Compiled {len(strings)} string IDs to {destination}")


def main():
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument("sources", type=Path, nargs="+")
  parser.add_argument("destination", type=Path)
  args = parser.parse_args()
  try:
    compile_strings(args.sources, args.destination)
  except (OSError, ValueError) as error:
    parser.exit(1, f"{error}\n")


if __name__ == "__main__":
  main()
